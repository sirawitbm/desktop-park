def pet(id, name, behavior, frames, speed=1.0):
    return {"id": id, "name": name, "kind": "pet", "behavior": behavior,
            "palette": PAL, "frames": frames, "speed": speed}


def deco(id, name, frames, behavior="stay"):
    return {"id": id, "name": name, "kind": "deco", "behavior": behavior,
            "palette": PAL, "frames": frames}



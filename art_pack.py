def _witch_cat(cat_rows):
    """The cat, recoloured slate grey with yellow eyes, wearing a witch hat.
    (v0.5: lighter than black, so it doesn't vanish on dark wallpapers.)"""
    recolour = str.maketrans({"c": "s", "C": "S", "e": "y"})
    hat = [
        "............k...",
        "...........kVk..",
        "..........kVVVk.",
        "..........kOOOk.",
        ".........kvvvvvk",
    ]
    return hat + [r.translate(recolour) for r in cat_rows[2:]]



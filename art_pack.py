def _lift(sprite_id, mapping):
    """v0.5 readability: lighter body colours for the darkest Halloween sprites."""
    table = str.maketrans(mapping)
    for a in HALLOWEEN:
        if a["id"] == sprite_id:
            a["frames"] = [[row.translate(table) for row in f] for f in a["frames"]]


